'use strict';
const assert=require('node:assert/strict');
const Core=require('../learning_experience_core.js');
const L=require('../learning_lab.js');
const Snap=require('../observation_snapshots.js');
assert.equal(Snap.SCHEMA,'seethetruth-observation-snapshot-v1');
const graph=L.preset('residual');
const numeric=Core.inspectGraph(graph,{numeric:true,id:'learning_studio'});
const portable=Snap.create(Core,numeric,'residual baseline');
assert.equal(portable.kind,'graph');
assert.equal(portable.numeric,true);
assert.equal(portable.label,'residual baseline');
assert.equal(portable.input.nodes.length,graph.nodes.length);
assert.equal(Snap.route(Core,portable),'learn.html');
assert.equal(Snap.describe(Core,portable).replayVerified,false);
assert.deepEqual(Snap.restore(Core,portable).record.graph,numeric.graph);
assert.equal(Snap.restore(Core,portable).restored,true);
assert.equal(Core.compareRecords(numeric,Snap.restore(Core,portable).record).valueEqual,true);
const staticGraph=Core.inspectGraph(graph,{numeric:false,id:'learning_studio'});
const staticSnap=Snap.create(Core,staticGraph);
assert.equal(staticSnap.numeric,false);
assert.equal(Snap.restore(Core,staticSnap).record.numericOk,false);
assert.equal(Core.observe(Snap.restore(Core,staticSnap).record).traceAvailable,false);
const changed=structuredClone(portable);
changed.input.nodes.find(n=>n.id==='x').params.seed=987;
assert.throws(()=>Snap.restore(Core,changed),/replayed source result differs/);
const badChecksum=structuredClone(portable);badChecksum.checksum='fnv1a32:deadbeef:123';
assert.throws(()=>Snap.restore(Core,badChecksum),/replayed source result differs/);
const wrongDomain=structuredClone(portable);wrongDomain.engine='invented.js';
assert.throws(()=>Snap.restore(Core,wrongDomain),/graph source identity mismatch/);
const fake=structuredClone(portable);fake.evidence='GPU_ACTUAL';
assert.throws(()=>Snap.restore(Core,fake),/source evidence changed/);
const badSize=structuredClone(portable);badSize.label='x'.repeat(200000);
assert.throws(()=>Snap.validate(badSize),/size/);
const unknown=structuredClone(portable);unknown.extra='trust';
assert.throws(()=>Snap.validate(unknown),/unexpected envelope field/);
const nonFinite=structuredClone(portable);nonFinite.input.nodes[0].params.seed=NaN;
assert.throws(()=>Snap.validate(nonFinite),/non-finite numeric/);
const w=Core.executeLab('wan_ffn','trace',{options:{seed:17,tokens:3,dim:4,hidden:8}});
const wanSnap=Snap.create(Core,w,'source pinned');
assert.equal(wanSnap.kind,'specialized_execution');
assert.equal(wanSnap.numeric,false);
assert.equal(Snap.route(Core,wanSnap),'wan_ffn_lab.html');
assert.equal(Snap.restore(Core,wanSnap).record.evidence,w.evidence);
assert.equal(Core.compareRecords(w,Snap.restore(Core,wanSnap).record).valueEqual,true);
const drift=structuredClone(wanSnap);drift.input.options.seed=18;
assert.throws(()=>Snap.restore(Core,drift),/replayed source result differs/);
const fabricated=structuredClone(wanSnap);fabricated.engine='not-real.js';
assert.throws(()=>Snap.describe(Core,fabricated),/unregistered source engine/);
const worker=Core.executeLab('deepinfer_worker','simulate',{
 steps:[{mode:'prompt',sequenceIds:['A']},{mode:'decode',sequenceIds:[1]}],
 options:{zeroOverhead:true}});
const workerSnap=Snap.create(Core,worker);
assert.equal(Snap.restore(Core,workerSnap).record.stateTrace.schema,worker.stateTrace.schema);
assert.equal(Snap.route(Core,workerSnap),'deepinfer_worker_lab.html');
const pair=Core.executeLab('deepinfer_prefill','inspect_pair',{voteInput:{decodeStep:4,allInterval:2,anyInterval:4,ranks:[
 {waitingSchedulable:true,canActuallySchedule:true,cacheUsage:.2},
 {waitingSchedulable:false,canActuallySchedule:false,cacheUsage:.2}]},chunkInput:{tokens:['TEXT','TEXT'],cached:0,maxBatchedTokens:2}});
assert.equal(Snap.restore(Core,Snap.create(Core,pair)).record.stateTrace.steps.length,pair.stateTrace.steps.length);
assert.throws(()=>Snap.create(Core,{kind:'graph'}),/graph replay requires/);
const original=JSON.stringify(numeric);
Snap.create(Core,numeric);
assert.equal(JSON.stringify(numeric),original,'creating snapshot cannot mutate accepted run');
console.log('PORTABLE_OBSERVATION_SNAPSHOT_PASS: source-replay, graph/state, evidence, bounds, corruption and isolation');
