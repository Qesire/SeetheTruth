'use strict';
const assert=require('node:assert/strict');
const E=require('../engineering_journey_engine.js'),P=require('../engineering_training_pipeline.js');
const base={seed:7,samplerSeed:19,lr:0.08,microBatchSize:2,accumulationSteps:4,weightDecay:0.01,warmupSteps:3,totalSteps:24,minLrScale:0.15,maxGradNorm:1};
const close=(a,b,eps=1e-12)=>assert.ok(Math.abs(a-b)<=eps,'math mismatch: '+a+' vs '+b);
assert.equal(P.create().config.microBatchSize,2);
assert.equal(new Set(P.shuffledIndices(19,0)).size,24);
assert.deepEqual(P.shuffledIndices(19,0),P.shuffledIndices(19,0));
assert.notDeepEqual(P.shuffledIndices(19,0),P.shuffledIndices(19,1));
close(P.scheduledLr(base,1),base.lr/3);
close(P.scheduledLr(base,3),base.lr);
close(P.scheduledLr(base,24),base.lr*base.minLrScale);
close(P.scheduledLr(base,100),base.lr*base.minLrScale);
assert.throws(()=>P.create({accumulationSteps:0}),/accumulationSteps/);
assert.throws(()=>P.create({microBatchSize:0}),/microBatchSize/);
assert.throws(()=>P.create({maxGradNorm:0}),/maxGradNorm/);
assert.throws(()=>P.create({warmupSteps:25}),/warmupSteps/);
const one=P.create({...base,microBatchSize:8,accumulationSteps:1});
const split=P.create(base);
assert.deepEqual(split.previewBatch().indices.map(x=>x.index),one.previewBatch().indices.slice(0,2).map(x=>x.index));
assert.equal(split.previewBatch().cursor,0,'peek must not consume');
assert.throws(()=>split.optimizerStep(),/finish every microbatch/);
const initial=split.diagnostic().modelDigest;
const first=split.microStep();
assert.equal(first.sampleCount,2);assert.equal(first.microStep,1);
assert.equal(split.diagnostic().modelDigest,initial,'microbatch must not update weights');
assert.equal(split.modelStep,0);assert.equal(split.pendingMicroSteps,1);
for(let j=1;j<4;j++)split.microStep();
const result=split.optimizerStep();
const full=one.train(1);
assert.equal(result.examples,8);assert.equal(result.microSteps,4);
assert.equal(result.step,1);assert.equal(split.pendingMicroSteps,0);
close(result.batchLoss,full.batchLoss);
close(result.rawGradNorm,full.rawGradNorm);
for(let k=0;k<64;k++)close(one.checkpoint().model.weights[k],split.checkpoint().model.weights[k],1e-12);
const resumed=P.create(base),continuous=P.create(base);
continuous.train(8);
resumed.train(3);
resumed.microStep();resumed.microStep();
const snap=JSON.parse(JSON.stringify(resumed.checkpoint()));
assert.equal(snap.pending.microSteps,2);
const restored=P.create(base);const ret=restored.restore(snap);
assert.deepEqual(ret,{restored:true,optimizerStep:3,pendingMicroSteps:2,epoch:snap.sampler.epoch,cursor:snap.sampler.cursor});
restored.train(5);
for(const key of ['weights','firstMoment','secondMoment']){
 const expected=continuous.checkpoint().model[key],actual=restored.checkpoint().model[key];
 assert.deepEqual(actual,expected,'interrupted gradient accumulation must exactly reproduce uninterrupted optimizer state: '+key);
}
assert.deepEqual(restored.checkpoint(),continuous.checkpoint(),'cursor, epoch, optimizer and grad buffer must all match');
assert.deepEqual(restored.generate({seed:5,temperature:0.5}),continuous.generate({seed:5,temperature:0.5}));
const corrupt=JSON.parse(JSON.stringify(snap));corrupt.pending.indices.reverse();
assert.throws(()=>resumed.restore(corrupt),/lineage mismatch/);
assert.deepEqual(resumed.checkpoint(),snap,'invalid restore is atomic');
const badCursor=JSON.parse(JSON.stringify(snap));badCursor.sampler.cursor=7;
assert.throws(()=>resumed.restore(badCursor),/sampler position/);
const badDataset=JSON.parse(JSON.stringify(snap));badDataset.dataFingerprint='deadbeef';
assert.throws(()=>resumed.restore(badDataset),/dataset\/source mismatch/);
const badGrad=JSON.parse(JSON.stringify(snap));badGrad.pending.gradientSum[0]=null;
assert.throws(()=>resumed.restore(badGrad),/invalid accumulated gradient/);
const badCfg=JSON.parse(JSON.stringify(snap));badCfg.config.lr=0.03;
assert.throws(()=>resumed.restore(badCfg),/configuration mismatch/);
const completed=P.create(base);
const initialEval=completed.evaluate('train');
completed.train(24);
assert.equal(completed.modelStep,24);
assert.ok(completed.evaluate('train').loss<initialEval.loss-0.05);
