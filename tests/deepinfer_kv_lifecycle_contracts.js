assert.deepEqual(s.free,[5,6,2,4,1,3],'reverse free and tail-reuse FIFO ordering');
assert.equal(s.free.length,6);
assert.ok(K.verify(s));
assert.throws(()=>doOp(s,{op:'finish',id:'A'}),/already finished/);
assert.throws(()=>doOp(s,{op:'arrive',id:'A',tokenLen:1}),/duplicate request/);
