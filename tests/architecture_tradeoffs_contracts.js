'use strict';
const assert=require('node:assert/strict');
const T=require('../architecture_tradeoffs.js');
const g=T.gqa({layers:2,heads:8,kvHeads:2,headDim:16,context:10,batch:3,bytes:2});
assert.equal(g.bytes,2*2*3*10*2*16*2);
assert.equal(g.ratio,0.25);
assert.equal(g.mhaBytes,4*g.bytes);
assert.throws(()=>T.gqa({layers:1,heads:7,kvHeads:2,headDim:8,context:5}),/divisible/);
assert.throws(()=>T.gqa({layers:1,heads:8,kvHeads:2,headDim:8,context:0}),/integer/);
const m=T.moe({tokens:4,hidden:8,intermediate:16,experts:8,topK:2,sharedExperts:1});
assert.equal(m.totalExpertParameters,9*3*8*16);
assert.equal(m.activeExpertParametersPerToken,3*3*8*16);
assert.equal(m.approxExpertFlops,2*4*m.activeExpertParametersPerToken);
assert.throws(()=>T.moe({tokens:1,hidden:8,intermediate:8,experts:2,topK:3}),/topK/);
const l=T.loop({width:8,intermediate:16,steps:6,untiedLayers:6});
assert.equal(l.sharedParameters,4*64+3*8*16);
assert.equal(l.untiedParameters,6*l.sharedParameters);
assert.equal(l.perTokenProjectionFlops,2*6*l.sharedParameters);
assert.throws(()=>T.loop({width:8,intermediate:16,steps:1.5}),/integer/);
assert.throws(()=>T.gqa({layers:1,heads:1000000,kvHeads:1,headDim:10000,context:1000000,bytes:2}),/safe integer/);
const dense=T.gqa({layers:2,heads:8,kvHeads:8,headDim:16,context:10});
assert.equal(dense.bytes,dense.mhaBytes);
assert.equal(dense.saving,0);
console.log('Architecture tradeoffs: analytical identities and invalid-input contracts PASS');
