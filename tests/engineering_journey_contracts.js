'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const E=require('../engineering_journey_engine.js');
const root=path.resolve(__dirname,'..');
assert.equal(E.VOCAB.length,8);
assert.deepEqual(E.encode('我 爱 数学'),[0,1,3,5,7]);
assert.throws(()=>E.encode('我 不 存在'),/词表外/);
assert.equal(E.auditDataset().overlap.length,0);
assert.equal(E.auditDataset().trainPairs,24);
assert.equal(E.auditDataset().validationPairs,8);
assert.throws(()=>E.create({seed:0}),/seed/);
assert.throws(()=>E.create({lr:2}),/学习率/);
assert.throws(()=>E.create({batchSize:0}),/batchSize/);
assert.throws(()=>E.create({weightDecay:-1}),/weightDecay/);
for(const settings of [{seed:7,batchSize:1},{seed:42,batchSize:8},{seed:91,batchSize:16}]){
 const a=E.create(settings),b=E.create(settings);
 assert.deepEqual(a.checkpoint(),b.checkpoint(),'same seed + config should be reproducible');
 const f=a.forward('爱');
 assert.equal(f.logits.length,8);assert.equal(f.probs.length,8);
 assert.ok(Math.abs(f.probs.reduce((x,y)=>x+y,0)-1)<1e-14);
 const finite=a.gradientCheck();
 assert.ok(finite.absoluteError<1e-6,JSON.stringify(finite));
 assert.equal(a.inspectGradient().gradient.length,64);
 const pre=a.evaluate('train');assert.equal(pre.pairs,24);
 assert.equal(a.step,0,'inspection/evaluation must not update weights');
 const after=a.train(120);
 assert.equal(a.step,120);assert.ok(after.train.loss<pre.loss-0.05);
 assert.equal(after.step,a.checkpoint().step);
 assert.ok(after.gradNorm>0&&after.updateNorm>0);
 assert.ok(Number.isFinite(after.validation.perplexity));
 const snap=JSON.parse(JSON.stringify(a.checkpoint())),original=a.generate({seed:21,temperature:0.7,topK:3});
 assert.deepEqual(original,a.generate({seed:21,temperature:0.7,topK:3}),'seeded stochastic decode must be reproducible');
 assert.deepEqual(a.generate({seed:1,temperature:0}).tokens,a.generate({seed:999,temperature:0}).tokens,'greedy ignores RNG');
 assert.ok(original.trace.length>=1&&original.trace.length<=10);
 for(const x of original.trace)assert.notEqual(x.token,'<bos>','BOS must not be generated');
 a.trainStep();assert.equal(a.step,121);a.restore(snap);
 assert.deepEqual(a.checkpoint(),snap,'AdamW weights + moments + step must roundtrip');
 assert.deepEqual(a.generate({seed:21,temperature:0.7,topK:3}),original,'post-restore inference must be identical');
 const tampered={...snap,weights:snap.weights.slice(1)};
 assert.throws(()=>a.restore(tampered),/weights/);
 assert.deepEqual(a.checkpoint(),snap,'rejected snapshot must not mutate state');
 assert.throws(()=>a.restore({...snap,vocab:[...snap.vocab].reverse()}),/tokenizer/);
 assert.throws(()=>a.restore({...snap,secondMoment:snap.secondMoment.map(()=>-1)}),/second moment/);
 assert.throws(()=>a.restore({...snap,config:{...snap.config,seed:17}}),/config/);
 assert.throws(()=>a.generate({temperature:-1}),/temperature/);
 assert.throws(()=>a.generate({maxNewTokens:25}),/maxNewTokens/);
 assert.throws(()=>a.forward('未知词'),/unknown token/);
}
const html=fs.readFileSync(path.join(root,'engineering_journey.html'),'utf8');
const script=fs.readFileSync(path.join(root,'engineering_journey_ui.js'),'utf8');
new vm.Script(script);
for(const el of ['stages','run','result','answerSelect','next','progressFill','reset','metrics'])assert.ok(html.includes('id="'+el+'"'),el);
for(const file of ['engineering_journey_engine.js','engineering_journey_ui.js'])assert.ok(html.includes('src="'+file+'"'),file);
assert.ok(script.includes('12-stage')&&script.includes('training'));
assert.ok(script.includes('e.train(120)')&&script.includes('e.restore(state.snapshot)')&&script.includes('e.generate(args)'));
assert.ok(script.includes('state.done.add(i)')&&script.includes('Number(selected)!==explain().correct'));
for(const id of ['engineering_journey.html','engineering_journey_engine.js','engineering_journey_ui.js']){
 assert.ok(fs.readFileSync(path.join(root,'android/teaching-assets.txt'),'utf8').split(/\r?\n/).includes(id),'Android asset missing '+id);
}
assert.ok(fs.readFileSync(path.join(root,'teaching.html'),'utf8').includes('href="engineering_journey.html"'));
assert.ok(fs.readFileSync(path.join(root,'learn.html'),'utf8').includes('href="engineering_journey.html"'));
console.log('ENGINEERING_JOURNEY_PASS reproducible init, independent split, finite differences, AdamW training, checkpoint, deterministic decode, invalid cases, PC/Android assets');
