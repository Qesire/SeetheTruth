'use strict';
const assert=require('node:assert/strict'),B=require('../block_catalog.js'),L=require('../learning_lab.js'),C=require('../concept_flow.js'),K=require('../block_knowledge.js');
const run=(kind,inputs,params={})=>B.execute({id:'oracle',kind,params},inputs).values;
const sigmoid=x=>1/(1+Math.exp(-x)),near=(a,b)=>assert.ok(Math.abs(a-b)<1e-10,a+' != '+b);
const scores=[[2,0,1]],biased=[[2,9,1]],indices=[[1,0]];
const orig=JSON.stringify(scores);
const gates=run('router_gate_weights',{scores,indices},{mode:'sigmoid',normalize:true});
const den=sigmoid(0)+sigmoid(2);
near(gates[0][0],sigmoid(0)/den);near(gates[0][1],sigmoid(2)/den);
assert.equal(JSON.stringify(scores),orig,'router gate mutated original logits');
const experts=[[1,0],[0,1],[5,5]];
const sum=run('expert_bank_mix',{indices,gates,experts});near(sum[0][0],gates[0][1]);near(sum[0][1],gates[0][0]);
const other=run('router_gate_weights',{scores:biased,indices},{mode:'sigmoid',normalize:true});
assert.ok(Math.abs(gates[0][0]-other[0][0])>0.1,'biased gate should differ from canonical raw affinity');
const soft=run('router_gate_weights',{scores,indices},{mode:'softmax',normalize:true});
near(soft[0][0]+soft[0][1],1);
assert.throws(()=>run('router_gate_weights',{scores,indices:[[3]]}),/out of range/);
assert.throws(()=>run('expert_bank_mix',{indices:[[3]],gates:[[1]],experts}),/out of range/);
for(const kind of ['router_gate_weights','expert_bank_mix'])assert.ok(K.get(kind).refs.length);
const preset=L.preset('moe_route');
assert.equal(preset.nodes.length,11);
const trace=L.evaluate(preset),contract=C.evaluate(preset);
assert.deepEqual(trace.steps.map(v=>v.shape),contract.steps.map(v=>v.shape));
assert.equal(trace.steps.at(-1).id,'mix');
assert.deepEqual(trace.steps.at(-1).shape,[3,4]);
const steps=Object.fromEntries(trace.steps.map(step=>[step.id,step.values]));
assert.deepEqual(trace.steps.find(step=>step.id==='select').shape,[3,2]);
assert.deepEqual(trace.steps.find(step=>step.id==='gather').shape,[6,4]);
steps.affinity.forEach((row,t)=>row.forEach((v,e)=>near(v,sigmoid(steps.score[t][e]))));
steps.biased.forEach((row,t)=>row.forEach((v,e)=>near(v,steps.affinity[t][e]+steps.bias[0][e])));
steps.gates.forEach((row,t)=>{
  near(row.reduce((a,b)=>a+b,0),1);
  const sum=steps.select[t].reduce((v,e)=>v+steps.affinity[t][e],0);
  row.forEach((w,k)=>near(w,steps.affinity[t][steps.select[t][k]]/sum));
  steps.mix[t].forEach((v,d)=>near(v,steps.select[t].reduce((acc,e,k)=>acc+row[k]*steps.experts[e][d],0)));
});
console.log('MoE independent selection/gate and weighted expert combine PASS');
