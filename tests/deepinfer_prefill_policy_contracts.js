'use strict';
const assert=require('node:assert/strict'),P=require('../deepinfer_prefill_policy.js');
const rank=(want,scheduled=true,cacheUsage=.2)=>({waitingSchedulable:want,canActuallySchedule:scheduled,cacheUsage});
const ready=[rank(true),rank(true)];
let v=P.vote({decodeStep:0,allInterval:2,anyInterval:4,ranks:ready});
assert.equal(v.point,'ALL');
assert.equal(v.step,'prompt');
assert.deepEqual(v.perRank,['prompt','prompt']);
assert.equal(v.nextDecodeStep,0);
v=P.vote({decodeStep:1,allInterval:2,anyInterval:4,ranks:ready});
assert.equal(v.point,'NONE');assert.equal(v.step,'decode');
v=P.vote({decodeStep:2,allInterval:2,anyInterval:4,ranks:[rank(true),rank(false)]});
assert.equal(v.point,'ALL');assert.equal(v.step,'decode','ALL demands every rank wants prefill');
v=P.vote({decodeStep:4,allInterval:2,anyInterval:4,ranks:[rank(true),rank(false)]});
assert.equal(v.point,'ANY','ANY point wins over co-occurring ALL');
assert.equal(v.step,'prompt');
assert.deepEqual(v.perRank,['prompt','empty-prompt']);
assert.equal(v.scheduledCount,1);
v=P.vote({decodeStep:4,allInterval:2,anyInterval:4,ranks:[rank(true,false),rank(false)]});
assert.equal(v.point,'ANY');assert.equal(v.step,'decode');
assert.equal(v.secondVoteFallback,true,'all rank allocation attempts failed');
assert.equal(v.nextDecodeStep,5,'fallback must not reset decode counter');
v=P.vote({decodeStep:4,allInterval:2,anyInterval:4,watermark:.8,ranks:[
 rank(true,true,.9),rank(false,true,.1)]});
assert.equal(v.step,'decode','watermark stops prefill');
assert.equal(P.vote({engine:'COMPLETION',ranks:ready}).step,'decode');
assert.equal(P.vote({engine:'PROMPT',ranks:ready}).step,'prompt');
assert.throws(()=>P.vote({decodeStep:0,allInterval:0,ranks:ready}),/allInterval/);
assert.throws(()=>P.vote({decodeStep:0,ranks:[{waitingSchedulable:true,cacheUsage:.1}]}),/flags/);
const tokens=['TEXT','IMG','PAD','PAD','PAD','TEXT','TEXT'];
assert.equal(P.insidePad(tokens,2),true);
assert.equal(P.insidePad(tokens,4),true);
assert.equal(P.insidePad(tokens,1),false,'image beginning is allowed split boundary');
assert.deepEqual(P.adjustImageChunk(tokens,0,4,true),{q:5,boundary:5,adjusted:true});
assert.deepEqual(P.adjustImageChunk(tokens,0,4,false),{q:1,boundary:1,adjusted:true});
const clipped=P.chunk({tokens,maxBatchedTokens:4,cpAlign:1});
assert.equal(clipped.outcome,'scheduled');
assert.equal(clipped.q,1);
assert.equal(clipped.remaining,6);
assert.equal(clipped.status,'WAITING');
assert.equal(clipped.imageAdjusted,true);
assert.equal(clipped.charged,1);
const fullImage=P.chunk({tokens,maxBatchedTokens:5,cpAlign:1});
assert.equal(fullImage.q,5);
assert.equal(fullImage.remaining,2);
const done=P.chunk({tokens,maxBatchedTokens:8,cpAlign:2});
assert.equal(done.q,7);
assert.equal(done.status,'RUNNING');
assert.equal(done.charged,8,'CP padding counts 8 tokens for 7 Q');
const checkpoint=P.chunk({tokens:['TEXT','TEXT','TEXT','TEXT','TEXT'],cached:0,
 maxBatchedTokens:5,checkpoints:[3]});
assert.equal(checkpoint.q,3);
assert.equal(checkpoint.remaining,2);
const already=P.chunk({tokens:['TEXT','TEXT','TEXT','TEXT'],cached:2,maxBatchedTokens:4,cpAlign:1});
assert.equal(already.q,2);assert.equal(already.status,'RUNNING');
const cannot=P.chunk({tokens,maxBatchedTokens:4,chunkedPrefill:false});
assert.equal(cannot.outcome,'deferred','partial prefill rejected without chunked mode');
const wait=P.chunk({tokens,cached:1,maxBatchedTokens:2,alreadyBatched:0,scheduledCount:1});
assert.equal(wait.outcome,'deferred');
assert.equal(wait.why,'zero Q after image boundary');
assert.throws(()=>P.chunk({tokens,cached:1,maxBatchedTokens:2,alreadyBatched:0,scheduledCount:0}),/zero Q/);
assert.throws(()=>P.chunk({tokens,cached:0,maxBatchedTokens:5,cpAlign:0}),/cpAlign/);
assert.equal(P.chunk({tokens:['PAD','TEXT'],maxBatchedTokens:4}).outcome,'scheduled',
 'unpaired PAD labels do not invent a protected image span');
console.log('DEEPINFER_PREFILL_POLICY_PASS source ALL/ANY two-stage votes, MM image-pad splits, CP budgets, checkpoint and guard');
