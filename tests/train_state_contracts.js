'use strict';
const assert=require('node:assert/strict');
const L=require('../learning_lab.js'),T=require('../train_state.js'),G=require('../graph_autodiff.js');
const copy=x=>JSON.parse(JSON.stringify(x)),near=(a,b,tol=1e-11)=>assert.ok(Math.abs(a-b)<tol,a+' ~= '+b);
const start=L.preset('trainable_core'),original=JSON.stringify(start);
const W=start.nodes.find(n=>n.id==='shared_weight');
assert.equal(W.kind,'parameter');assert.deepEqual([W.params.values.length,W.params.values[0].length],[2,2]);
assert.equal(W.params.optimizer.t,0);
assert.equal(T.inspect(start)[0].id,'shared_weight');
const f=L.evaluate(start),g=G.backward(start,f);
assert.deepEqual(g.gradients.shared_weight.length,2);
const result1=T.step(start,{lr:0.01});
assert.equal(JSON.stringify(start),original,'optimizer transaction mutated original graph');
assert.equal(result1.records.length,1);
assert.equal(result1.records[0].id,'shared_weight');
assert.equal(result1.records[0].optimizerStep,1);
const w1=result1.graph.nodes.find(n=>n.id==='shared_weight');
assert.equal(w1.params.optimizer.t,1);
assert.notDeepEqual(w1.params.values,W.params.values);
near(result1.beforeLoss,f.steps.at(-1).values[0][0]);
near(result1.afterLoss,L.evaluate(result1.graph).steps.at(-1).values[0][0]);
const result2=T.step(result1.graph,{lr:0.01});
const w2=result2.graph.nodes.find(n=>n.id==='shared_weight');
assert.equal(w2.params.optimizer.t,2);
assert.deepEqual(result2.graph.edges,start.edges);
assert.deepEqual(result2.graph.nodes.map(n=>n.id),start.nodes.map(n=>n.id));
assert.ok(Number.isFinite(result1.delta)&&Number.isFinite(result2.delta));
const saved=JSON.stringify(result2.graph),restored=L.validateGraph(JSON.parse(saved));
assert.deepEqual(restored,result2.graph,'save/load discarded optimizer state');
const result3=T.step(restored,{lr:0.01});
const fromOriginal=T.step(result2.graph,{lr:0.01});
assert.deepEqual(result3.graph,fromOriginal.graph,'JSON round-trip changed future optimizer updates');
const tamper=copy(restored);tamper.nodes.find(n=>n.id==='shared_weight').params.optimizer.v[0][0]=-1;
assert.throws(()=>L.validateGraph(tamper),/nonnegative/);
const bad=copy(restored);bad.nodes.find(n=>n.id==='shared_weight').params.values=[[1,2,3]];
assert.throws(()=>L.validateGraph(bad),/dimensions/);
const huge=copy(restored);huge.nodes.find(n=>n.id==='shared_weight').params.values[0][0]=Infinity;
assert.throws(()=>L.validateGraph(huge),/matrix/);
assert.throws(()=>T.step(L.preset('autodiff_core')),/trainable Parameter/);
const stale=copy(restored);stale.edges=stale.edges.filter(e=>e.from!=='shared_weight');
assert.throws(()=>T.step(stale),/connected|端口/);
console.log('Persistent parameter training PASS: two AdamW steps, immutable undo snapshot, JSON state restore and shape/nonfinite rejection; loss '+result1.beforeLoss+' -> '+result1.afterLoss+' -> '+result2.afterLoss);
