"""Acceptance: installed block packs are first-class freely connected blocks,
not private laboratory demos or fake registered names."""
import threading,unittest,sys
from pathlib import Path
from http.server import ThreadingHTTPServer
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from atlas_server import Handler
from playwright.sync_api import sync_playwright
DEST=Path('block_extension_screenshots')
class BlockPackBrowser(unittest.TestCase):
 @classmethod
 def setUpClass(cls):
  DEST.mkdir(parents=True,exist_ok=True)
  cls.server=ThreadingHTTPServer(('127.0.0.1',0),Handler)
  cls.thread=threading.Thread(target=cls.server.serve_forever,daemon=True)
  cls.thread.start();cls.pw=sync_playwright().start()
  cls.browser=cls.pw.chromium.launch(headless=True,args=['--no-sandbox'])
  cls.root='http://127.0.0.1:'+str(cls.server.server_port)
 @classmethod
 def tearDownClass(cls):
  cls.browser.close();cls.pw.stop();cls.server.shutdown();cls.server.server_close()
 def test_numeric_paper_modules_combine_with_standard_add(self):
  p=self.browser.new_page(viewport={'width':1580,'height':980})
  errors=[];p.on('pageerror',lambda e:errors.append(str(e)))
  self.assertEqual(p.goto(self.root+'/learn.html').status,200)
  p.locator('#studyMode').select_option('numeric')
  p.locator('[data-preset="extension_paper_composition"]').click()
  self.assertTrue(p.locator('[data-node="lora"]').count())
  self.assertTrue(p.locator('[data-node="dora"]').count())
  self.assertTrue(p.locator('[data-node="blend"]').count())
  p.locator('#run').click()
  p.wait_for_function("window.SeetheTruthMicroscopeWorkbench.stageCount===8")
  p.locator('#computeMicroscope .cmp-step').nth(5).click()
  self.assertEqual(p.locator('#computeMicroscope .cmp-substep').count(),6)
  p.locator('#computeMicroscope .cmp-substep').nth(1).click()
  self.assertIn('GEMM',p.locator('#computeMicroscope .cmp-meta').inner_text())
  self.assertGreaterEqual(p.locator('#computeMicroscope .cmp-terms tr').count(),2)
  p.screenshot(path=str(DEST/'universal-paper-pack-in-editor.png'),full_page=False,animations='disabled')
  p.locator('#computeMicroscope .cmp-step').nth(6).click()
  self.assertEqual(p.locator('#computeMicroscope .cmp-substep').count(),7)
  p.locator('#computeMicroscope .cmp-substep').last.click()
  self.assertIn('W_eff',p.locator('#computeMicroscope .cmp-meta').inner_text())
  self.assertEqual(errors,[]);p.close()
 def test_real_five_axis_video_then_online_paper_pack_on_phone(self):
  p=self.browser.new_page(viewport={'width':390,'height':844},device_scale_factor=2,is_mobile=True,has_touch=True)
  errors=[];p.on('pageerror',lambda e:errors.append(str(e)))
  self.assertEqual(p.goto(self.root+'/learn.html?edition=teaching').status,200)
  p.locator('#studyMode').select_option('numeric')
  p.locator('[data-preset="extension_video_composition"]').click()
  p.locator('#run').click()
  p.wait_for_function("window.SeetheTruthMicroscopeWorkbench.stageCount===4")
  p.locator('#computeMicroscope .cmp-step').last.click()
  self.assertIn('Output 1 × 3 × 2 × 2 × 2',p.locator('#computeMicroscope .cmp-meta').inner_text())
  self.assertEqual(p.locator('#computeMicroscope .cmp-axes select').count(),3)
  first=p.locator('#computeMicroscope .cmp-cell').first.inner_text()
  p.locator('#computeMicroscope .cmp-axes select').nth(1).select_option('2')
  second=p.locator('#computeMicroscope .cmp-cell').first.inner_text()
  self.assertNotEqual(first,second,'switching time axis must change original underlying numerical frame')
  p.screenshot(path=str(DEST/'universal-named-video-pack-phone.png'),full_page=True,animations='disabled')
  p.locator('[data-preset="extension_online_attention"]').click()
  p.locator('#run').click()
  p.wait_for_function("window.SeetheTruthMicroscopeWorkbench.stageCount===5")
  p.locator('#computeMicroscope .cmp-step').nth(3).click()
  self.assertGreaterEqual(p.locator('#computeMicroscope .cmp-substep').count(),7)
  p.locator('#computeMicroscope .cmp-substep').nth(1).click()
  self.assertIn('Scores',p.locator('#computeMicroscope .cmp-meta').inner_text())
  self.assertGreater(p.locator('#computeMicroscope .cmp-terms tr').count(),2)
  p.screenshot(path=str(DEST/'universal-online-attention-pack-phone.png'),full_page=True,animations='disabled')
  self.assertEqual(errors,[]);p.close()
 def test_pack_owned_named_axis_lesson_auto_appears_and_composes(self):
  p=self.browser.new_page(viewport={'width':1450,'height':920})
  errors=[];p.on('pageerror',lambda e:errors.append(str(e)))
  self.assertEqual(p.goto(self.root+'/learn.html').status,200)
  button=p.locator('[data-preset="extension_named_axis_composition"]')
  self.assertEqual(button.count(),1,'pack recipe auto-discovery must mount its own lesson')
  self.assertIn('具名轴广播',button.inner_text())
  p.locator('#studyMode').select_option('numeric')
  button.click()
  self.assertEqual(p.locator('[data-node="add"]').count(),1)
  self.assertEqual(p.locator('[data-node="swap"]').count(),1)
  self.assertEqual(p.locator('[data-node="native"]').count(),1)
  self.assertEqual(p.locator('[data-node="delta"]').count(),1)
  p.locator('#run').click()
  p.wait_for_function("window.SeetheTruthMicroscopeWorkbench.stageCount===7")
  p.locator('#computeMicroscope .cmp-step').nth(6).click()
  self.assertIn('Output 3 × 3',p.locator('#computeMicroscope .cmp-meta').inner_text())
  self.assertIn('0',p.locator('#computeMicroscope .cmp-cell').first.inner_text())
  p.locator('#computeMicroscope .cmp-step').nth(3).click()
  self.assertEqual(p.locator('#computeMicroscope .cmp-substep').count(),2)
  p.locator('#computeMicroscope .cmp-substep').nth(1).click()
  self.assertIn('具名',p.locator('#computeMicroscope .cmp-meta').inner_text())
  p.screenshot(path=str(DEST/'registry-owned-named-axis-composition.png'),full_page=False,animations='disabled')
  self.assertEqual(errors,[]);p.close()
if __name__=='__main__':unittest.main()
