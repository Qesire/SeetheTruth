'use strict';
const assert=require('node:assert/strict');
const B=require('../block_catalog.js'),L=require('../learning_lab.js'),C=require('../concept_flow.js'),K=require('../block_knowledge.js');
const run=(kind,inputs,params={})=>B.execute({id:'unit',kind,params},inputs);
const close=(a,b,eps=1e-10)=>assert.ok(Math.abs(a-b)<eps,a+' != '+b);
const previous=[[1,2],[3,4]],newRow=[[5,6]],old=JSON.stringify(previous);
const write=run('cache_write_segment',{cache:previous,segment:newRow},{start:2,capacity:5});
assert.deepEqual(write.values,[[1,2],[3,4],[5,6]]);
assert.equal(JSON.stringify(previous),old,'cache write mutated its incoming state');
assert.equal(write.internals.cache_state.endPos,3);
assert.deepEqual(run('cache_read_prefix',{cache:write.values},{length:2}).values,[[1,2],[3,4]]);
const replaced=run('cache_write_segment',{cache:write.values,segment:[[9,9]]},{start:1,capacity:5});
assert.deepEqual(replaced.values,[[1,2],[9,9],[5,6]],'overwriting a historical position preserves suffix');
assert.throws(()=>run('cache_write_segment',{cache:previous,segment:newRow},{start:3,capacity:5}),/skip unwritten/);
assert.throws(()=>run('cache_write_segment',{cache:previous,segment:newRow},{start:2,capacity:2}),/capacity/);
assert.throws(()=>run('cache_write_segment',{cache:previous,segment:[[1]]},{start:2,capacity:5}),/dimension/);
assert.throws(()=>run('cache_read_prefix',{cache:previous},{length:3}),/committed prefix/);
const Cstate=[[1,2,3],[-1,3,2]],Wk=[[2,1],[-1,2],[.5,-.25]],Q=[[4,2]];
const k=Cstate.map(row=>Wk[0].map((_,j)=>row.reduce((s,v,d)=>s+v*Wk[d][j],0)));
const scores=k.map(row=>Q[0].reduce((sum,v,j)=>sum+v*row[j],0));
const absorbed=run('query_weight_absorb',{query:Q,keyWeight:Wk}).values;
assert.deepEqual([absorbed.length,absorbed[0].length],[1,3]);
Cstate.forEach((row,s)=>close(scores[s],absorbed[0].reduce((total,v,r)=>total+v*row[r],0)));
assert.throws(()=>run('query_weight_absorb',{query:[[1,2]],keyWeight:[[1,2,3]]}),/features/);
const g=L.preset('mla_cache'),numeric=L.evaluate(g),concept=C.evaluate(g);
assert.equal(g.nodes.length,35);
assert.deepEqual(numeric.steps.map(z=>z.shape),concept.steps.map(z=>z.shape),'concept/numeric shape inconsistency');
const N=Object.fromEntries(numeric.steps.map(z=>[z.id,z.values]));
assert.deepEqual(N.c_write.slice(0,2),N.c_old);
assert.deepEqual(N.c_write[2],N.c_new[0]);
assert.deepEqual(N.pe_write.slice(0,2),N.pe_old_rope);
assert.deepEqual(N.pe_write[2],N.pe_new_rope[0]);
for(const pair of [['score_explicit','score_abs'],['sum_explicit','sum_abs'],['probs_explicit','probs_abs'],['out_explicit','out_abs']]){
 const A=N[pair[0]],B=N[pair[1]];
 assert.deepEqual(A.map(row=>row.length),B.map(row=>row.length));
 A.forEach((row,t)=>row.forEach((v,j)=>close(v,B[t][j],1e-9)));
}
N.difference.flat().forEach(v=>close(v,0,1e-9));
close(N.probs_abs[0].reduce((a,b)=>a+b,0),1);
assert.equal(N.c_read.length,3);assert.equal(N.pe_read.length,3);
for(const name of ['cache_write_segment','cache_read_prefix','query_weight_absorb'])assert.ok(K.get(name)?.refs?.length>0);
console.log('MLA cache: pure snapshots, causal decode prefix, absorbed key scores and value-before-projection equality PASS');
