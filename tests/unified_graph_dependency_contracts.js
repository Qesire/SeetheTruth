'use strict';
const assert=require('node:assert/strict');
const L=require('../learning_lab.js');
const Branch=require('../branch_execution.js');
const Ready=require('../graph_readiness.js');

const graph=L.preset('residual');
const index=L.indexGraph(graph);
assert.deepEqual(index.ordered.map(n=>n.id),L.order(graph).map(n=>n.id));
assert.equal(index.incomingByPort.get('sum:a'),'x');
assert.equal(index.incomingByPort.get('sum:b'),'act');
assert.deepEqual(index.parents.get('sum'),['x','act']);
assert.deepEqual(index.children.get('x'),['fc','sum']);
const sub=Branch.slice(graph,'act');
assert.deepEqual(new Set(sub.nodes.map(n=>n.id)),new Set(['x','fc','act']));
assert.equal(sub.edges.length,2);
const full=Ready.check(graph);
assert.equal(full.executable,true);
assert.equal(full.nodes.length,graph.nodes.length);
const selected=Ready.check(graph,{targetId:'act'});
assert.equal(selected.executable,true);
assert.equal(selected.nodes.length,3);
const disconnected=L.validateGraph({...graph,edges:graph.edges.filter(e=>!(e.to==='sum'&&e.port==='b'))});
const partial=Ready.check(disconnected);
assert.equal(partial.executable,false);
assert.ok(partial.nodes.some(n=>n.id==='sum'&&n.status==='missing'));
const cycle=L.validateGraph({...graph,edges:[...graph.edges,{from:'sum',to:'fc',port:'x'}].filter(e=>!(e.to==='fc'&&e.port==='x'))});
assert.throws(()=>L.indexGraph(cycle),/循环计算依赖/);
console.log('UNIFIED_GRAPH_DEPENDENCY_PASS');
