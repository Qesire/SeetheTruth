/* Conservative graph-to-PyTorch compiler for a validated subset of Learning Studio.
 * It rejects unsupported operators rather than emitting pseudo-code.
 */
(function(root,factory){
 'use strict';
 const api=factory(typeof module==='object'&&module.exports?require('./learning_lab.js'):root.SeetheTruthLearning);
 if(typeof module==='object'&&module.exports)module.exports=api;
 root.SeetheTruthTorchExport=api;
})(typeof window!=='undefined'?window:{},function(L){
 'use strict';
 const SUPPORTED=Object.freeze(['input','linear','rmsnorm','silu','add','mul','matmul','softmax','mse']);
 const ports={linear:['x'],rmsnorm:['x'],silu:['x'],add:['a','b'],mul:['a','b'],matmul:['a','b'],softmax:['x'],mse:['prediction','target']};
 function compile(raw){
  const graph=L.validateGraph(raw),nodes=L.order(graph);
  const unsupported=nodes.filter(n=>!SUPPORTED.includes(n.kind));
  if(unsupported.length)throw Error('PyTorch export unavailable for: '+unsupported.map(n=>n.id+' ('+n.kind+')').join(', '));
  const conn=new Map(graph.edges.map(e=>[e.to+':'+e.port,e.from]));
  for(const n of nodes)for(const port of ports[n.kind]||[])if(!conn.has(n.id+':'+port))
   throw Error('Missing input port: '+n.id+'.'+port);
  // Evaluate the original micro-graph first; this guards shape incompatibilities.
  L.evaluate(graph);
  const lines=[
   '# Auto-generated by SeetheTruth. Requires Python 3 and PyTorch.',
   '# Deterministic educational computation, not imported model weights or runtime trace.',
   '# Double precision is used to approximate the browser Float64 interpreter.',
   'import math',
   'import torch',
   'torch.set_grad_enabled(False)',
   'values = {}',
   '',
   'def _weight(node_id, row, col):',
   '    h = 2166136261',
   '    for ch in f"{node_id}:{row}:{col}":',
   '        h = ((h ^ ord(ch)) * 16777619) & 0xffffffff',
   '    return ((h % 2001) - 1000) / 2600.0',
   ''
  ];
  const name=n=>JSON.stringify(n.id);
  for(const n of nodes){
   const dst='values['+name(n)+']';
   const inp=port=>'values['+JSON.stringify(conn.get(n.id+':'+port))+']';
   lines.push('# '+n.id+' / '+n.kind);
   switch(n.kind){
    case 'input':{
     const {rows,width,seed}=n.params;
     lines.push(dst+' = torch.tensor([[math.sin((i+1)*(j+1)*0.71 + '+seed+'*0.37)*0.8 for j in range('+width+')] for i in range('+rows+')], dtype=torch.float64)');
     break;
    }
    case 'linear':{
     const x=inp('x'),o=n.params.out;
     lines.push('_x = '+x);
     lines.push('_w = torch.tensor([[_weight('+name(n)+', j, k) for k in range(_x.shape[1])] for j in range('+o+')], dtype=torch.float64)');
     lines.push('_b = torch.tensor([_weight('+name(n)+', 97, j) for j in range('+o+')], dtype=torch.float64)');
     lines.push(dst+' = _x @ _w.T + _b');
     break;
    }
    case 'rmsnorm':{
     const x=inp('x');
     lines.push('_x = '+x);
     lines.push(dst+' = _x * torch.rsqrt(torch.mean(_x.square(), dim=-1, keepdim=True) + '+n.params.epsilon+')');
     break;
    }
    case 'silu':lines.push(dst+' = torch.nn.functional.silu('+inp('x')+')');break;
    case 'add':lines.push(dst+' = '+inp('a')+' + '+inp('b'));break;
    case 'mul':lines.push(dst+' = '+inp('a')+' * '+inp('b'));break;
    case 'matmul':lines.push(dst+' = '+inp('a')+' @ '+inp('b'));break;
    case 'softmax':lines.push(dst+' = torch.softmax('+inp('x')+', dim=-1)');break;
    case 'mse':lines.push(dst+' = torch.mean(('+inp('prediction')+' - '+inp('target')+').square()).reshape(1, 1)');break;
   }
  }
  lines.push('',"if __name__ == '__main__':");
  for(const n of nodes)lines.push('    print('+name(n)+', tuple(values['+name(n)+'].shape), values['+name(n)+'].tolist())');
  return {code:lines.join('\n')+'\n',nodeCount:nodes.length,operators:[...new Set(nodes.map(n=>n.kind))]};
 }
 return Object.freeze({SUPPORTED,compile});
});
